function buildVocabList(): readonly string[] {
  const seen = new Set<string>();
  const combined: string[] = [];

  const append = (word: string) => {
    const clean = word.trim();
    if (!clean || seen.has(clean)) return;
    seen.add(clean);
    combined.push(clean);
  };

  for (const w of CORE_HADITH_VOCAB) {
    append(w);
  }
  for (const block of EXPANDED_VOCAB_BLOCKS) {
    for (const w of block.split(/\s+/)) {
      append(w);
    }
  }

  return combined;
}

