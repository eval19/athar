function stripAlPrefix(normWord: string): string {
  return normWord.startsWith('ال') && normWord.length >= 4 ? normWord.slice(2) : normWord;
}

/**
 * Matches modern or colloquial Arabic terms against curated classical Hadith
 * concepts, returning up to 3 authentic classical search phrases when matched.
 */
export function findConceptExpansions(query: string): string[] {
  const normQuery = normalizeArabic(query);
  if (!normQuery) return [];

  const tokens = extractContentTokens(query);
  const tokenVariants = new Set<string>();
  for (const tok of tokens) {
    tokenVariants.add(tok);
    tokenVariants.add(stripAlPrefix(tok));
  }
  const strippedFull = normQuery
    .split(/\s+/)
    .map(stripAlPrefix)
    .join(' ');

  const scored: Array<{ queries: readonly string[]; score: number; order: number }> = [];

  for (let i = 0; i < ARABIC_HADITH_CONCEPTS.length; i++) {
    const concept = ARABIC_HADITH_CONCEPTS[i];
    let bestScore = 0;

    for (const rawTrigger of concept.triggers) {
      const normTrig = normalizeArabic(rawTrigger);
      const bareTrig = normTrig.split(/\s+/).map(stripAlPrefix).join(' ');

      if (normTrig.includes(' ')) {
        if (normQuery.includes(normTrig) || strippedFull.includes(bareTrig)) {
          bestScore = Math.max(bestScore, 3);
        }
      } else if (tokenVariants.has(normTrig) || tokenVariants.has(bareTrig)) {
        bestScore = Math.max(bestScore, 2);
      }
    }

    if (bestScore > 0) {
      scored.push({ queries: concept.queries, score: bestScore, order: i });
    }
  }

  scored.sort((a, b) => (b.score !== a.score ? b.score - a.score : a.order - b.order));

  const out: string[] = [];
  for (const entry of scored) {
    for (const q of entry.queries) {
      if (!out.includes(q)) {
        out.push(q);
        if (out.length >= 3) return out;
      }
    }
  }
  return out;
}
